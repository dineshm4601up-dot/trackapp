-- ===========================================================================
-- 6. agent_add_task_proof()
-- ===========================================================================
-- Registers a file the agent uploaded through a server-issued signed URL.
-- Checks ownership, task state, the server-generated path, and the stored
-- object's real size and type; the app has already checked the file's bytes.
create or replace function public.agent_add_task_proof(
  p_task_id     uuid,
  p_path        text,
  p_proof_type  text,
  p_file_name   text,
  p_sha256      text,
  p_description text default null
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_agent uuid := public.current_agent_id();
  v_task  public.tasks%rowtype;
  v_obj   record;
  v_size  bigint;
  v_mime  text;
  v_id    uuid;
  v_max   numeric := public.app_setting('proof_max_file_bytes', 10485760);
begin
  if v_agent is null then
    raise exception using errcode = '42501', message = 'UNAUTHORIZED';
  end if;
  select * into v_task from public.tasks where id = p_task_id for update;
  if not found or v_task.agent_id is distinct from v_agent or v_task.status = 'DRAFT' then
    raise exception using errcode = 'P0001', message = 'TASK_NOT_FOUND';
  end if;
  if v_task.status not in ('CHECKED_IN', 'IN_PROGRESS') then
    raise exception using errcode = 'P0001', message = 'INVALID_TASK_STATUS';
  end if;
  if public.proof_path_task_id(p_path) is distinct from p_task_id then
    raise exception using errcode = 'P0001', message = 'INVALID_PATH';
  end if;
  if p_proof_type not in ('PHOTO', 'DOCUMENT') then
    raise exception using errcode = 'P0001', message = 'INVALID_PROOF_TYPE';
  end if;
  if p_sha256 is null or p_sha256 !~ '^[0-9a-f]{64}$' then
    raise exception using errcode = 'P0001', message = 'INVALID_FILE';
  end if;
  if char_length(coalesce(p_file_name, '')) > 200 or char_length(coalesce(p_description, '')) > 500 then
    raise exception using errcode = 'P0001', message = 'TEXT_TOO_LONG';
  end if;

  select o.metadata into v_obj from storage.objects o where o.bucket_id = 'task-proofs' and o.name = p_path;
  if not found then
    raise exception using errcode = 'P0001', message = 'FILE_NOT_FOUND';
  end if;
  v_size := (v_obj.metadata ->> 'size')::bigint;
  v_mime := v_obj.metadata ->> 'mimetype';
  if v_size is null or v_size <= 0 or v_size > v_max then
    raise exception using errcode = 'P0001', message = 'FILE_TOO_LARGE';
  end if;
  if not (
       (p_proof_type = 'PHOTO' and v_mime in ('image/jpeg', 'image/png', 'image/webp'))
    or (p_proof_type = 'DOCUMENT' and v_mime in ('application/pdf', 'image/jpeg', 'image/png', 'image/webp'))
  -- (CASE is parenthesised: PL/pgSQL ends an IF condition at the first THEN.)
  ) or v_mime is distinct from (case substring(p_path from '\.([a-z]+)$')
                   when 'jpg' then 'image/jpeg' when 'png' then 'image/png'
                   when 'webp' then 'image/webp' when 'pdf' then 'application/pdf' end) then
    raise exception using errcode = 'P0001', message = 'INVALID_FILE_TYPE';
  end if;
  if exists (select 1 from public.task_proofs where task_id = p_task_id and sha256 = p_sha256) then
    raise exception using errcode = 'P0001', message = 'PROOF_DUPLICATE';
  end if;

  insert into public.task_proofs (task_id, agent_id, proof_type, storage_path, file_name, mime_type,
                                  file_size_bytes, description, sha256)
  values (p_task_id, v_agent, p_proof_type, p_path, nullif(btrim(coalesce(p_file_name, '')), ''), v_mime,
          v_size, nullif(btrim(coalesce(p_description, '')), ''), p_sha256)
  returning id into v_id;
  return v_id;
end;
$$;

revoke execute on function public.agent_add_task_proof(uuid, text, text, text, text, text) from public, anon;
grant execute on function public.agent_add_task_proof(uuid, text, text, text, text, text) to authenticated;

-- ===========================================================================
-- 7. Audit: execution actions
-- ===========================================================================
create or replace function public.audit_row_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  entity    text := tg_argv[0];
  old_row   jsonb := case when tg_op <> 'INSERT' then to_jsonb(old) end;
  new_row   jsonb := case when tg_op <> 'DELETE' then to_jsonb(new) end;
  old_diff  jsonb;
  new_diff  jsonb;
  keys      text[];
  action    text;
begin
  if tg_op = 'UPDATE' then
    select jsonb_object_agg(n.key, old_row -> n.key), jsonb_object_agg(n.key, n.value)
      into old_diff, new_diff
      from jsonb_each(new_row) n
     where n.key <> 'updated_at' and n.value is distinct from old_row -> n.key;
    if new_diff is null then
      return null; -- no-op update
    end if;
    select array_agg(k order by k) into keys from jsonb_object_keys(new_diff) k;

    action := case
      when entity = 'TASK' and new_diff ? 'status' then
        case new_diff ->> 'status'
          when 'ASSIGNED'            then case when old_diff ->> 'status' = 'DRAFT' then 'ASSIGN_TASK' else 'UPDATE_TASK' end
          when 'ACCEPTED'            then 'ACCEPT_TASK'
          when 'ON_THE_WAY'          then 'START_TRAVEL'
          when 'ARRIVED'             then 'MARK_ARRIVED'
          when 'CHECKED_IN'          then 'TASK_CHECK_IN'
          when 'IN_PROGRESS'         then 'START_TASK'
          when 'COMPLETED'           then 'COMPLETE_TASK'
          when 'PARTIALLY_COMPLETED' then 'PARTIALLY_COMPLETE_TASK'
          when 'FAILED'              then 'REPORT_TASK_FAILURE'
          when 'CANCELLED'           then 'CANCEL_TASK'
          when 'VERIFIED'            then 'VERIFY_TASK'
          else 'UPDATE_TASK'
        end
      when entity = 'TASK' and new_diff ? 'agent_id' then 'REASSIGN_TASK'
      when entity = 'TASK'
           and keys <@ array['scheduled_date', 'scheduled_start_time', 'scheduled_end_time'] then 'RESCHEDULE_TASK'
      when entity = 'TASK_PRODUCT' and new_diff ? 'delivered_quantity' then 'UPDATE_DELIVERY_QUANTITY'
      when entity = 'TASK_PRODUCT' then 'UPDATE_TASK_PRODUCT'
      when entity = 'CASH_COLLECTION' then 'CORRECT_CASH_COLLECTION'
      when keys = array['is_active'] then
        case when (new_diff ->> 'is_active')::boolean then 'ACTIVATE_' else 'DEACTIVATE_' end || entity
      else 'UPDATE_' || entity
    end;
  else
    old_diff := old_row - 'updated_at';
    new_diff := new_row - 'updated_at';
    action := case
      when entity = 'TASK_PRODUCT' and tg_op = 'INSERT' then 'ADD_TASK_PRODUCT'
      when entity = 'TASK_PRODUCT' and tg_op = 'DELETE' then 'REMOVE_TASK_PRODUCT'
      when entity = 'CASH_COLLECTION' and tg_op = 'INSERT' then 'SUBMIT_CASH_COLLECTION'
      when entity = 'TASK_PROOF' and tg_op = 'INSERT' then 'UPLOAD_TASK_PROOF'
      when tg_op = 'INSERT' then 'CREATE_' || entity
      else 'DELETE_' || entity
    end;
  end if;

  insert into public.audit_logs (actor_user_id, action, entity_type, entity_id, old_values, new_values)
  values (auth.uid(), action, entity, (coalesce(new_row, old_row) ->> 'id')::uuid, old_diff, new_diff);
  return null;
end;
$$;

revoke execute on function public.audit_row_change() from public, anon, authenticated;

drop trigger if exists task_proofs_audit on public.task_proofs;
create trigger task_proofs_audit
  after insert or update or delete on public.task_proofs
  for each row execute function public.audit_row_change('TASK_PROOF');

commit;
