// Regenerates src/types/database.types.ts from the live database schema.
// Usage: npm run db:types   (requires SUPABASE_DB_URL in .env.local)
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

try {
  process.loadEnvFile(".env.local");
} catch {
  // Fall back to the existing environment (e.g. CI secrets).
}

const dbUrl = process.env.SUPABASE_DB_URL;
if (!dbUrl) {
  console.error("SUPABASE_DB_URL is not set (see .env.example).");
  process.exit(1);
}

// Run npx through node directly (no shell), so the connection string is never
// interpreted by a shell. npm_execpath points at npm's CLI when run via npm.
const npmCli = process.env.npm_execpath;
if (!npmCli) {
  console.error("Run this through npm: npm run db:types");
  process.exit(1);
}
const npxCli = path.join(path.dirname(npmCli), "npx-cli.js");

const output = execFileSync(
  process.execPath,
  [npxCli, "--yes", "supabase@2", "gen", "types", "typescript", "--db-url", dbUrl, "--schema", "public"],
  { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] },
);

const target = "src/types/database.types.ts";
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, `// Generated by \`npm run db:types\` — do not edit by hand.\n${output}`);
console.log(`Wrote ${target}`);
